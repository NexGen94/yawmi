"""System habits seed: `api/db/seed/habits.json` becomes one idempotent upsert.

`habits.json` (taken from the acceptance criteria of `GOAL-2031.md`) is the single source.
`render_seed_sql` turns it into one `INSERT ... ON CONFLICT (code) DO UPDATE` statement that

* writes the system definition (title, outcome, criterion, kind, unit, target, period, schedule),
* never touches the user-editable parts of a system habit: `anchor` and the reminders,
* fills `start_day` with today in Riyadh on the first run only, so no day before the app existed
  is counted as missed, and keeps whatever `start_day` a habit already has afterwards.

`api/db/seed/habits.sql` is that statement written to disk (`api/tools/export_seed_sql.py`): the
server loader runs it with psql, and `seed_habits` runs the very same text through asyncpg.
It is a single statement, so it is atomic under both.
"""

import json
from pathlib import Path
from typing import Any, Protocol

# api/yawmi/db/seed.py -> api/db/seed/habits.json. A source-tree default, like the migrations.
SEED_DIR = Path(__file__).resolve().parents[2] / "db" / "seed"
HABITS_JSON = SEED_DIR / "habits.json"
HABITS_SQL = SEED_DIR / "habits.sql"

# Every column of `yawmi.habits` a seed row carries (`updated_at` is set by the statement).
COLUMNS = (
    "code",
    "title_ar",
    "goal_ref",
    "outcome",
    "ac_ref",
    "kind",
    "unit",
    "target_per_period",
    "period",
    "schedule_kind",
    "weekday_mask",
    "every_n",
    "anchor_day",
    "anchor",
    "start_day",
    "end_day",
    "system",
    "created_by",
    "active",
)

# What a re-seed refreshes: the system definition. Not `anchor` (the user's cue) and not the
# lifecycle state (`active`, `end_day`); `start_day` is handled separately (COALESCE).
_REFRESHED = (
    "title_ar",
    "goal_ref",
    "outcome",
    "ac_ref",
    "kind",
    "unit",
    "target_per_period",
    "period",
    "schedule_kind",
    "weekday_mask",
    "every_n",
    "anchor_day",
    "system",
    "created_by",
)

TODAY_RIYADH = "(now() AT TIME ZONE 'Asia/Riyadh')::date"

# The generated file lints the same with or without `api/.sqlfluff`.
_HEADER = """\
-- Generated by api/tools/export_seed_sql.py from api/db/seed/habits.json: do not edit by hand.
-- System habits from GOAL-2031.md. Safe to run again: it keeps anchor, reminders and start_day.
-- sqlfluff:max_line_length:100
-- sqlfluff:indentation:tab_space_size:2
-- sqlfluff:rules:capitalisation.literals:capitalisation_policy:upper
-- sqlfluff:rules:capitalisation.functions:ignore_words:now
-- sqlfluff:rules:references.keywords:ignore_words:system,anchor,code,kind,unit,period,active"""

_MAX_LINE = 96  # wrapped value lines stay under the 100-column lint limit


class _Executes(Protocol):
    """The slice of an asyncpg connection (or pooled connection) the seeder needs."""

    async def execute(self, query: str, /) -> str: ...


def load_habits(path: Path | None = None) -> list[dict[str, Any]]:
    """Read the seed rows from `habits.json` (or from `path`)."""
    source = HABITS_JSON if path is None else path
    habits = json.loads(source.read_text(encoding="utf-8"))
    if not isinstance(habits, list):
        raise TypeError(f"{source}: expected a JSON list of habits")
    return habits


def _literal(value: Any) -> str:
    """A SQL literal for a JSON scalar (standard-conforming strings: only `'` is special)."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):  # before int: bool is an int subclass
        return "TRUE" if value else "FALSE"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return str(int(value)) if value.is_integer() else repr(value)
    if isinstance(value, str):
        if "\x00" in value:
            raise ValueError("a seed string contains a NUL character")
        return "'" + value.replace("'", "''") + "'"
    raise TypeError(f"cannot render {type(value).__name__} as a SQL literal")


def _validate(habits: list[dict[str, Any]]) -> None:
    if not habits:
        raise ValueError("the seed list is empty")
    seen: set[str] = set()
    for habit in habits:
        code = habit.get("code")
        missing = [c for c in COLUMNS if c not in habit]
        unknown = sorted(set(habit) - set(COLUMNS))
        if missing:
            raise ValueError(f"habit {code!r} lacks columns: {', '.join(missing)}")
        if unknown:
            raise ValueError(f"habit {code!r} has unknown columns: {', '.join(unknown)}")
        if code in seen:
            raise ValueError(f"duplicate habit code: {code!r}")
        seen.add(code)
        if habit["start_day"] is not None:
            raise ValueError(
                f"habit {code!r}: start_day must be null in the seed (the seeder fills it)"
            )


def _wrap(values: list[str], indent: str) -> list[str]:
    """Pack comma-separated values into lines no longer than `_MAX_LINE` characters."""
    lines: list[str] = []
    current = ""
    for index, value in enumerate(values):
        piece = value + ("," if index < len(values) - 1 else "")
        if current and len(indent) + len(current) + 1 + len(piece) > _MAX_LINE:
            lines.append(indent + current)
            current = piece
        else:
            current = f"{current} {piece}" if current else piece
    lines.append(indent + current)
    return lines


def render_seed_sql(habits: list[dict[str, Any]]) -> str:
    """The one-statement idempotent upsert for `habits` (all `start_day` must be null)."""
    _validate(habits)
    rows: list[str] = []
    for habit in habits:
        values = [TODAY_RIYADH if c == "start_day" else _literal(habit[c]) for c in COLUMNS]
        rows.append("(\n" + "\n".join(_wrap(values, "  ")) + "\n)")
    assignments = [f"  {c} = excluded.{c}" for c in _REFRESHED]
    assignments.append(f"  start_day = COALESCE(yawmi.habits.start_day, {TODAY_RIYADH})")
    assignments.append("  updated_at = now()")
    return (
        _HEADER
        + "\nINSERT INTO yawmi.habits (\n"
        + "\n".join(_wrap(list(COLUMNS), "  "))
        + "\n)\nVALUES\n"
        + ",\n".join(rows)
        + "\nON CONFLICT (code) DO UPDATE SET\n"
        + ",\n".join(assignments)
        + ";\n"
    )


async def seed_habits(conn: _Executes) -> int:
    """Run the seed statement on `conn`; return how many habits it inserted or refreshed."""
    tag = await conn.execute(render_seed_sql(load_habits()))
    return int(tag.rsplit(" ", 1)[-1])
